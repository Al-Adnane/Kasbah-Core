/**
 * Kasbah CLI Shim — wraps every detected AI CLI with a governed shim.
 *
 * For each detected CLI (claude, ollama, aider, codex, gh copilot, llm, …)
 * we write a shim script to ~/.kasbah/shims/<name> that:
 *   1. Records the invocation (timestamp, args, cwd, parent process) to the audit chain
 *   2. Pre-flight scans args that look like prompts
 *   3. Sets HTTPS_PROXY so all provider calls route through Kasbah
 *   4. Execs the real binary with the same args
 *   5. Streams stdout/stderr back unchanged
 *
 * Activation: user runs `eval "$(curl -s http://127.0.0.1:8788/v1/shim/init)"`
 * which prepends ~/.kasbah/shims to PATH.
 *
 *   GET  /v1/shim/init                — shell snippet to source
 *   GET  /v1/shim/list                — which CLIs have shims
 *   POST /v1/shim/install             — write shims for all detected CLIs
 *   POST /v1/shim/uninstall           — remove all shims
 *   GET  /v1/shim/recent              — last 50 governed CLI invocations
 */

