'use strict';

/**
 * "Kasbah saved you" digest — weekly / on-demand proof of protection.
 * Aggregates intervention session counters + optional usage meter into a
 * shareable Slack/email-friendly summary. Source of truth is intervention.js
 * snapshots (and usage-meter when an API key is present).
 */

const intervention = require('./intervention.js');

function formatDigest(snapshot, opts = {}) {
  const c = snapshot?.counters || {};
  const saved = c.saved || 0;
  const blocked = c.hard_block || 0;
  const warned = c.warning_toast || 0;
  const silent = c.silent_pass || 0;
  const mute = c.mute_block || 0;
  const would = c.would_have_blocked || 0;
  const scanned = silent + warned + blocked + mute;

  const lines = [
    `Kasbah saved you ${saved} time${saved === 1 ? '' : 's'} this ${opts.period || 'session'}.`,
    scanned ? `Scanned ${scanned} AI action${scanned === 1 ? '' : 's'} · ${silent} Silent Pass · ${warned} Warning · ${blocked} Hard Block.` : 'No AI actions scanned yet.',
    would ? `Would have blocked ${would} more (enforcement credits spent — Mute Block).` : null,
    opts.receiptCount ? `${opts.receiptCount} portable proof${opts.receiptCount === 1 ? '' : 's'} issued — shareable at /verify/:id.` : null,
    opts.trustGrade ? `AI Trust Grade: ${opts.trustGrade.grade} (${opts.trustGrade.score}) — ${opts.trustGrade.label}.` : null,
  ].filter(Boolean);

  const headline = saved > 0
    ? `Kasbah blocked ${saved} leak${saved === 1 ? '' : 's'} before they left your device.`
    : 'Kasbah is watching silently — no leaks yet.';

  return {
    headline,
    lines,
    slack: {
      text: headline,
      blocks: [
        { type: 'header', text: { type: 'plain_text', text: 'Kasbah saved you' } },
        { type: 'section', text: { type: 'mrkdwn', text: lines.map((l) => `• ${l}`).join('\n') } },
      ],
    },
    email: {
      subject: headline,
      bodyText: lines.join('\n'),
      bodyHtml: `<h2>${headline}</h2><ul>${lines.map((l) => `<li>${l}</li>`).join('')}</ul>` +
        `<p><a href="/verify">Verify a receipt</a> · Generated by Kasbah</p>`,
    },
    footer: 'This report was generated by Kasbah — portable proof of AI safety.',
    counters: { ...c },
    period: opts.period || 'session',
    generatedAt: new Date().toISOString(),
  };
}

function build(clientKey, opts = {}) {
  return formatDigest(intervention.snapshot(clientKey), opts);
}

module.exports = { build, formatDigest };
